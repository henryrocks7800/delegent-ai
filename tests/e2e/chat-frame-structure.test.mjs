// The chat surface is one hand-authored HTML document, and nothing checked its
// SHAPE.
//
// On 2026-09-12 a change removed the "start a fresh chat" nudge card and left
// two of its lines behind: the button, and one closing tag. HTML has no
// compiler. The browser silently re-parented everything after that extra tag,
// so `#app` ended early and the composer became a child of the document body
// instead, rendering off the bottom of the screen. The app shipped to Android,
// iOS and the web app with NO TEXT BOX, and an orphan button that nothing could
// dismiss. Every existing test stayed green throughout: they assert on source
// strings and on behaviour with the DOM stubbed, and neither notices a document
// that parses into the wrong tree. Alex found it on his phone.
//
// So this file parses the document and asserts the tree. It runs against every
// shipped copy, because the mobile asset, the bundled TypeScript and the web
// app's own copy are three files that are meant to agree and are generated by
// two different scripts.
import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';

// The web app's copy is generated by apps/webapp/scripts/sync-chat-webview.mjs
// and is gitignored, so it is absent in a fresh checkout until the web app is
// built. It is checked when it is there and skipped out loud when it is not:
// the two tracked copies are the ones that must always hold.
const SURFACES = {
  'mobile asset': 'apps/mobile/assets/chat-webview/index.html',
  'mobile bundle': 'apps/mobile/src/chat/chatWebViewHtml.ts',
  'web app copy': 'apps/webapp/public/chat-frame/index.html',
};
const GENERATED = new Set(['web app copy']);

// The HTML void elements and nothing else. The inline SVG icons in this
// document write their leaves with explicit closing tags, so treating those as
// void makes every one of them look like an unmatched close.
const VOID_TAGS = new Set(['area', 'base', 'br', 'col', 'embed', 'hr', 'img', 'input',
  'link', 'meta', 'source', 'track', 'wbr']);

const read = (path) => readFileSync(new URL('../../' + path, import.meta.url), 'utf8');
const readIfBuilt = (surface, path) => {
  try {
    return read(path);
  } catch (err) {
    if (GENERATED.has(surface) && err.code === 'ENOENT') return null;
    throw err;
  }
};

/**
 * Parse the document into a tree of elements.
 *
 * Comments are stripped FIRST. A comment may legitimately contain angle
 * brackets, including the very tag it is describing, and an earlier version of
 * this parser was fooled by exactly that while it was being written to catch a
 * markup bug. A checker that markup can mislead is not a checker.
 */
function parse(html) {
  const withoutComments = html.replace(/<!--[\s\S]*?-->/g, '');
  const body = withoutComments.slice(withoutComments.indexOf('<body'));
  const root = { tag: 'root', id: '', classes: [], children: [], parent: null };
  const stack = [root];
  const unmatchedCloses = [];
  const re = /<(\/?)([a-zA-Z][\w-]*)((?:"[^"]*"|'[^']*'|[^>"'])*?)(\/?)>/g;
  let match;
  while ((match = re.exec(body))) {
    const [, closing, rawTag, attrs, selfClosed] = match;
    const tag = rawTag.toLowerCase();
    if (closing) {
      // The scan starts at <body>, so </html> closes something opened before it.
      if (tag === 'html') break;
      const at = stack.findLastIndex((node) => node.tag === tag);
      if (at <= 0) { unmatchedCloses.push(tag); continue; }
      stack.length = at;
      continue;
    }
    const node = {
      tag,
      id: /\sid="([^"]*)"/.exec(attrs)?.[1] ?? '',
      classes: (/\sclass="([^"]*)"/.exec(attrs)?.[1] ?? '').split(/\s+/).filter(Boolean),
      children: [],
      parent: stack[stack.length - 1],
    };
    stack[stack.length - 1].children.push(node);
    // Raw-text elements. This document's inline script builds message bubbles
    // from template strings, so its source is full of tags that are not markup.
    // Reading them as markup is how a checker invents faults that are not there.
    if (tag === 'script' || tag === 'style') {
      const end = body.toLowerCase().indexOf(`</${tag}`, re.lastIndex);
      re.lastIndex = end === -1 ? body.length : end + tag.length + 3;
      continue;
    }
    if (!VOID_TAGS.has(tag) && !selfClosed) stack.push(node);
  }
  return { root, unmatchedCloses, stillOpen: stack.slice(1).map((node) => node.tag) };
}

const find = (node, predicate) => {
  if (predicate(node)) return node;
  for (const child of node.children) {
    const hit = find(child, predicate);
    if (hit) return hit;
  }
  return null;
};
const byId = (root, id) => find(root, (node) => node.id === id);
const byClass = (root, cls) => find(root, (node) => node.classes.includes(cls));
const describe = (node) => {
  const path = [];
  for (let cursor = node; cursor && cursor.tag !== 'root'; cursor = cursor.parent) {
    path.unshift(cursor.tag + (cursor.id ? '#' + cursor.id : ''));
  }
  return path.join(' > ');
};

for (const [surface, path] of Object.entries(SURFACES)) {
  test(`${surface}: the composer is inside the app frame, where it can be seen`, (t) => {
    const html = readIfBuilt(surface, path);
    if (html === null) return t.skip(`${path} is generated by the web app build and is not present`);
    const { root, unmatchedCloses, stillOpen } = parse(html);

    // The two faults an extra or missing tag produces, named separately so a
    // failure says which one happened.
    assert.deepEqual(unmatchedCloses, [],
      'closing tags with nothing open to close: every one of these silently re-parents the rest of the document');
    assert.deepEqual(stillOpen, [],
      'elements left open at the end of the document');

    const app = byId(root, 'app');
    assert.ok(app, '#app is the flex column that fills the viewport');

    // The two children that make the screen usable. Being a DESCENDANT is not
    // enough and being present is not enough: the layout gives #app the
    // viewport height and lays its own children out, so anything that lands
    // outside it is painted past the bottom of the screen.
    for (const [what, node] of [['#messages', byId(root, 'messages')], ['.composer', byClass(root, 'composer')]]) {
      assert.ok(node, `${what} is missing from ${surface}`);
      assert.equal(node.parent?.id, 'app',
        `${what} must be a direct child of #app, found at ${describe(node)}`);
    }

    // Order matters: the messages scroll, the composer is pinned under them.
    const childIds = app.children.map((node) => node.id || '.' + node.classes.join('.'));
    assert.ok(childIds.indexOf('messages') < childIds.indexOf('.composer'),
      'the composer must come after the message list');

    // And the controls a person actually needs to send a message.
    const input = byId(root, 'input');
    const send = byId(root, 'sendBtn');
    assert.equal(input?.tag, 'textarea', 'the text box itself');
    assert.equal(send?.tag, 'button', 'the send button');
    for (const [what, node] of [['the text box', input], ['send', send]]) {
      assert.ok(find(byClass(root, 'composer'), (candidate) => candidate === node),
        `${what} must live inside the composer, found at ${describe(node)}`);
    }
  });

  test(`${surface}: no control is left behind without the card that owned it`, (t) => {
    const html = readIfBuilt(surface, path);
    if (html === null) return t.skip(`${path} is generated by the web app build and is not present`);
    const { root } = parse(html);
    // The exact residue of the 2026-09-12 fault: a button whose container was
    // deleted around it. Any element carrying a component's class while that
    // component's own root is absent is the same bug wearing a different name.
    for (const [child, container] of [['fn-start', 'freshchat-nudge'], ['fn-close', 'freshchat-nudge'],
      ['lr-close', 'longrun-card'], ['lr-text', 'longrun-card'],
      ['quota-modal-cta', 'quota-modal'], ['tt-row', 'toolbar-tour']]) {
      const orphan = byClass(root, child);
      if (!orphan) continue;
      assert.ok(find(root, (node) => node.classes.includes(container) && find(node, (d) => d === orphan)),
        `.${child} exists but is not inside .${container}: found at ${describe(orphan)}`);
    }
  });
}

test('every shipped copy of the chat surface carries the same markup', () => {
  // Two different scripts generate the other two copies from the mobile asset,
  // so they drift silently if either is skipped. Compare the parsed shape
  // rather than the bytes: the web app copy legitimately injects a script block
  // for the parent-frame bridge.
  const shapes = Object.entries(SURFACES).map(([surface, path]) => {
    const html = readIfBuilt(surface, path);
    if (html === null) return null;
    const { root } = parse(html);
    const app = byId(root, 'app');
    return [surface, app.children.map((node) => `${node.tag}#${node.id}.${node.classes.join('.')}`).join('\n')];
  }).filter(Boolean);
  const [, reference] = shapes[0];
  for (const [surface, shape] of shapes.slice(1)) {
    assert.equal(shape, reference, `${surface} has drifted from the mobile asset: regenerate it`);
  }
});
