# Embeds the app's own typefaces in the chat WebView, so the conversation is set
# in the same Geist as the rest of the app instead of the phone's default sans.
#
#   python apps/mobile/scripts/build-chat-fonts.py
#   node scripts/regen-chat-webview-html.js
#
# The chat document is inline HTML with no files beside it, so each face is
# subset to Latin (plus the punctuation and currency a British user types) and
# inlined as a base64 WOFF between the @chat-fonts markers in
# assets/chat-webview/index.html. Anything outside the subset (emoji, other
# scripts) falls through to the system font named after it in the stack.
#
# Needs fontTools (pip install fonttools); WOFF uses zlib, so no brotli. The
# fonts come from node_modules, so run it after npm install. Commit the result;
# the app never runs this.
import base64
import io
import os
import re

from fontTools import subset
from fontTools.ttLib import TTFont

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
FONTS = os.path.join(ROOT, 'node_modules', '@expo-google-fonts')
HTML = os.path.join(ROOT, 'apps', 'mobile', 'assets', 'chat-webview', 'index.html')

FACES = [
    ('Geist', 400, 'normal', os.path.join(FONTS, 'geist', '400Regular', 'Geist_400Regular.ttf')),
    ('Geist', 500, 'normal', os.path.join(FONTS, 'geist', '500Medium', 'Geist_500Medium.ttf')),
    ('Geist', 600, 'normal', os.path.join(FONTS, 'geist', '600SemiBold', 'Geist_600SemiBold.ttf')),
    ('Instrument Serif', 400, 'italic', os.path.join(FONTS, 'instrument-serif', '400Regular_Italic', 'InstrumentSerif_400Regular_Italic.ttf')),
]

# The serif only sets a few display lines (the welcome, dialog titles, the
# voice caption), so it carries plain Latin and typographic punctuation only.
SERIF_UNICODES = list(range(0x20, 0x7F)) + [0xA3, 0xE9, 0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2026]

UNICODES = (
    list(range(0x20, 0x7F))        # Basic Latin
    + list(range(0xA0, 0x180))     # Latin-1 and Latin Extended-A (names, £, ©)
    + list(range(0x2010, 0x2028))  # dashes, curly quotes, bullet, ellipsis
    + list(range(0x2030, 0x203B))
    + [0x2044, 0x20AC, 0x2122, 0x2190, 0x2191, 0x2192, 0x2193, 0x2212, 0x2713]
)

START = '/* @chat-fonts:start (generated by apps/mobile/scripts/build-chat-fonts.py, do not edit) */'
END = '/* @chat-fonts:end */'


def woff_base64(path, unicodes):
    font = TTFont(path)
    options = subset.Options()
    options.flavor = 'woff'
    options.layout_features = ['kern', 'liga', 'calt', 'tnum', 'case']
    options.name_IDs = ['*']
    options.notdef_outline = True
    subsetter = subset.Subsetter(options=options)
    subsetter.populate(unicodes=unicodes)
    subsetter.subset(font)
    buffer = io.BytesIO()
    font.flavor = 'woff'
    font.save(buffer)
    return base64.b64encode(buffer.getvalue()).decode('ascii'), len(buffer.getvalue())


def main():
    rules = []
    for family, weight, style, path in FACES:
        data, size = woff_base64(path, SERIF_UNICODES if family == 'Instrument Serif' else UNICODES)
        print(f'{family} {weight} {style}: {size} bytes woff')
        rules.append(
            f"@font-face {{ font-family: '{family}'; font-style: {style}; font-weight: {weight}; "
            f"font-display: block; src: url(data:font/woff;base64,{data}) format('woff'); }}"
        )
    block = START + '\n' + '\n'.join(rules) + '\n' + END

    with open(HTML, 'r', encoding='utf-8', newline='') as handle:
        html = handle.read()
    pattern = re.compile(re.escape(START) + r'.*?' + re.escape(END), re.S)
    if not pattern.search(html):
        raise SystemExit('No @chat-fonts markers in index.html; add them inside <style> first.')
    html = pattern.sub(lambda _match: block, html)
    with open(HTML, 'w', encoding='utf-8', newline='') as handle:
        handle.write(html)
    print(f'Wrote the font block into {os.path.relpath(HTML, ROOT)}')


if __name__ == '__main__':
    main()
